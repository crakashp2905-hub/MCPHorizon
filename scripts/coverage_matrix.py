#!/usr/bin/env python3
"""P22-08: protocol × mechanism coverage, with runtime and outcome axes. Cell values: TEST = exercised through that protocol's real gate/rig in a test; ARENA = only in the P21 arena;
LIB = protocol-agnostic library test only; — = not covered. Every referenced evidence file must exist (checked)."""
import sys
from pathlib import Path
REPO = Path(__file__).resolve().parents[1]
P = ["mcp_modern", "mcp_legacy", "utcp_http", "utcp_cli", "websocket", "code_mode"]
M = {  # mechanism -> (evidence file, {protocol: value})
 "effect parity (P14)": ("tests/p14/test_equiv.py", dict(mcp_modern="TEST", mcp_legacy="TEST", utcp_http="TEST", utcp_cli="—", websocket="—", code_mode="TEST (test mediator)")),
 "signed effect proof (P13)": ("tests/p13/test_authz.py", dict(mcp_modern="LIB", mcp_legacy="LIB", utcp_http="LIB", utcp_cli="—", websocket="—", code_mode="LIB")),
 "attenuating delegation (P15)": ("tests/p15/test_deleg.py", dict(mcp_modern="LIB", mcp_legacy="LIB", utcp_http="LIB", utcp_cli="—", websocket="—", code_mode="LIB")),
 "epistemic evidence (P16)": ("tests/p16/test_epist.py", dict(mcp_modern="LIB", mcp_legacy="LIB", utcp_http="LIB", utcp_cli="—", websocket="—", code_mode="LIB")),
 "transactions (P17)": ("tests/p17/test_txn.py", dict(mcp_modern="LIB", mcp_legacy="LIB", utcp_http="LIB", utcp_cli="—", websocket="—", code_mode="LIB")),
 "persistent memory (P18)": ("tests/p18/test_memory.py", dict(mcp_modern="ARENA", mcp_legacy="—", utcp_http="ARENA", utcp_cli="—", websocket="—", code_mode="ARENA")),
 "contract drift (P19)": ("tests/p19/test_attest.py", dict(mcp_modern="LIB", mcp_legacy="LIB", utcp_http="LIB", utcp_cli="—", websocket="—", code_mode="LIB")),
 "adversarial arena (P21)": ("tests/p21/test_arena.py", dict(mcp_modern="ARENA", mcp_legacy="—", utcp_http="ARENA", utcp_cli="—", websocket="—", code_mode="ARENA")),
}
RUNTIME = [("CPython (CI default) on Linux, in-process", "yes"), ("other Python versions", "no matrix (P14-11 open)"), ("macOS / Windows", "no"), ("containers / separate processes", "no"), ("real network transports / live servers", "no (all synthetic)")]
OUTCOME = [("ALLOW", "tested"), ("DENY", "tested"), ("REVIEW", "tested"), ("UNKNOWN / UNVERIFIED", "tested for epistemic (P16) and contracts (P19); not for parity"), ("irreversible partial effect", "P17 synthetic KV only")]


def build():
    for f, _ in M.values():
        if not (REPO / f).exists(): raise SystemExit(f"missing evidence {f}")
    md = ["# Coverage matrix (generated by scripts/coverage_matrix.py)", "", "| Mechanism | " + " | ".join(P) + " |", "|---|" + "---|" * len(P)]
    md += [f"| {k} | " + " | ".join(v[P_] for P_ in P) + " |" for k, (f, v) in M.items()]
    md += ["", "`—` means NOT covered and must not be read as equivalent or safe. `LIB` means the mechanism is tested as a library, not enforced inside that protocol's production gate.", "", "## Runtime", ""] + [f"- {a}: {b}" for a, b in RUNTIME] + ["", "## Outcomes", ""] + [f"- {a}: {b}" for a, b in OUTCOME]
    return "\n".join(md) + "\n"


if __name__ == "__main__":
    out = build(); path = REPO / "docs/evidence/COVERAGE_MATRIX.md"
    if "--check" in sys.argv:
        if not path.exists() or path.read_text() != out: print("coverage matrix stale"); raise SystemExit(1)
        print("coverage matrix up to date")
    else: path.write_text(out); print(out)
