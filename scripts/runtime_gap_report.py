#!/usr/bin/env python3
"""P23-18: derive task status for P23..P30 from spec/acceptance.json (mapped or not) — no manual status. `--check` verifies the committed file is current."""
import json, os, re, sys
ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__))); OUT = os.path.join(ROOT, "docs/evidence/p23/BASELINE_GAP_REPORT.md")
spec = open(os.path.join(ROOT, "docs/MCPHORIZON_2_0_MASTER_SPEC.md")).read(); acc = json.load(open(os.path.join(ROOT, "spec/acceptance.json")))
tasks = {m.group(1): m.group(2) for m in re.finditer(r"\*\*(P(?:2[3-9]|30)-\d\d)\*\*\s+(.*)", spec)}
L = ["# P23–P30 baseline gap report (generated by scripts/runtime_gap_report.py)", "", "Status is derived: **MAPPED** = a passing acceptance command exists (still CANDIDATE, never VERIFIED); **UNMAPPED** = no acceptance evidence (not done, or needs an external party).", ""]
for ph in range(23, 31):
    ids = sorted(i for i in tasks if i.startswith(f"P{ph}-")); mapped = [i for i in ids if i in acc]
    L += [f"## P{ph}: {len(mapped)}/{len(ids)} mapped", ""] + [f"- `{i}` **{'MAPPED' if i in acc else 'UNMAPPED'}** — {tasks[i][:110]}" for i in ids if i not in acc] + [""]
txt = "\n".join(L) + "\n"
if "--check" in sys.argv: sys.exit(0 if open(OUT).read() == txt else (print("stale"), 1)[1])
open(OUT, "w").write(txt); print(txt[:400])
