#!/usr/bin/env python3
"""Parse docs/hardening/MODULE_COMPLETION_GATES.md into security_hardening/inventory.json (generated).

`--check` verifies the committed inventory equals a fresh render and the integrity rules hold:
  * every module/task in the document is present exactly once;
  * module status is never above CANDIDATE without a non-null independent_attestation;
  * a task may be `done` only with existing evidence paths AND a result digest (checked against the file);
  * `*-GATE` tasks can never be done without an attestation;
  * code paths are recorded with an `exists` flag (missing paths are reported, not hidden).
Classification of each open task is rule-based (see CLASS_RULES) plus explicit overrides in
security_hardening/overrides.json (task id -> {done, evidence, digest, class, note}).  Nothing is invented:
no completion percentage is computed from anything but done flags.
"""
import hashlib, json, os, re, sys
ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
DOC = os.path.join(ROOT, "docs/hardening/MODULE_COMPLETION_GATES.md")
OVR = os.path.join(ROOT, "security_hardening/overrides.json")
OUT = os.path.join(ROOT, "security_hardening/inventory.json")
BLK = os.path.join(ROOT, "security_hardening/BLOCKED.md")
STATUSES = ("UNMAPPED", "CANDIDATE", "INTEGRATED", "ADVERSARIAL_TESTED", "INDEPENDENTLY_VERIFIED", "HARDENED_FOR_SCOPE", "BLOCKED")
ABOVE_CANDIDATE = ("INDEPENDENTLY_VERIFIED", "HARDENED_FOR_SCOPE")
# Open-task classes (HEURISTIC keyword triage, not a feasibility proof).  EXTERNAL = needs a party/resource this workspace cannot supply.
CLASS_RULES = [
    ("EXTERNAL", r"independent(ly)? (review|reviewer|sandbox|sign|key-management|security|escape|verification|test-set|establish)|reviewer|usability study|accessibility testing|legal|licens|provenance audit|external|"
                 r"commission|certify|attach frozen tests/results|real user|user study|HSM|KMS|cloud|separate hosts|multiple processes and separate|official (protocol )?conformance|official .* suites|real servers|unmodified supported|kernel/architecture|pinned hardware|real agent frameworks|two real agent frameworks"),
    ("NEEDS_LIVE_ENV", r"live |real (agent|MCP|multi|browser|services|source|server)|actual (agent|gateway|sink|model|supported)|production|multi-host|failover|microVM|V8|Node escape|TLS|DNS|namespace|firewall"),
]
TASK = re.compile(r"^- \[( |x)\] \*\*([A-Z]\d{2}-(?:\d{2}|GATE))\*\* (.*)$")
MOD = re.compile(r"^### ([A-G]\d{2}) — (.+)$")
GATE = re.compile(r"^### Gate (G\d) — (.+)$")
WS = re.compile(r"^## (Workstream [A-G]) — (.+)$")


def parse(text):
    mods, gates, cur, ws, gate = [], [], None, None, None
    for ln in text.splitlines():
        m = WS.match(ln)
        if m: ws = f"{m.group(1)} — {m.group(2)}"; cur = gate = None; continue
        m = MOD.match(ln)
        if m: cur = dict(id=m.group(1), name=m.group(2).strip(), workstream=ws, code_paths_raw="", associated_work="", blocker="", tasks=[]); mods.append(cur); gate = None; continue
        m = GATE.match(ln)
        if m: gate = dict(id=m.group(1), name=m.group(2).strip(), items=[]); gates.append(gate); cur = None; continue
        if cur is not None:
            mm = re.match(r"^\*\*Current implementation:\*\* (.*?)\s*$", ln)
            if mm: cur["code_paths_raw"] = mm.group(1); continue
            mm = re.match(r"^\*\*Associated work:\*\* (.*?)\s*$", ln)
            if mm: cur["associated_work"] = mm.group(1); continue
            mm = re.match(r"^\*\*Known completion blocker:\*\* (.*?)\s*$", ln)
            if mm: cur["blocker"] = mm.group(1); continue
            mm = TASK.match(ln)
            if mm: cur["tasks"].append(dict(id=mm.group(2), text=mm.group(3).strip(), doc_checked=mm.group(1) == "x"))
        elif gate is not None and ln.startswith("- ["):
            gate["items"].append(dict(text=ln[6:].strip(), doc_checked=ln.startswith("- [x]")))
    return mods, gates


def code_paths(raw):
    out = []
    for p in re.findall(r"`([^`]+)`", raw):
        for q in re.split(r";\s*", p):
            q = q.strip()
            if q: out.append(dict(path=q, exists=os.path.exists(os.path.join(ROOT, q.rstrip("/")))))
    return out


def classify(task):
    if task["id"].endswith("-GATE"): return "EXTERNAL"
    for cls, rx in CLASS_RULES:
        if re.search(rx, task["text"], re.I): return cls
    return "DOABLE_HERE"


def digest(path):
    h = hashlib.sha256()
    with open(os.path.join(ROOT, path), "rb") as f: h.update(f.read())
    return h.hexdigest()


def render():
    mods, gates = parse(open(DOC, encoding="utf-8").read())
    ovr = json.load(open(OVR)) if os.path.exists(OVR) else {}
    ovr_mod = ovr.get("modules", {}); ovr_task = ovr.get("tasks", {})
    inv = dict(source_doc="docs/hardening/MODULE_COMPLETION_GATES.md", doc_sha256=hashlib.sha256(open(DOC, "rb").read()).hexdigest(), modules=[], gates=[], note="Generated by scripts/hardening_inventory.py; never edit by hand. No percentage is computed.")
    for m in mods:
        mo = ovr_mod.get(m["id"], {})
        tasks = []
        for t in m["tasks"]:
            o = ovr_task.get(t["id"], {})
            tasks.append(dict(id=t["id"], text=t["text"], class_heuristic=o.get("class", classify(t)), done=bool(o.get("done", False)),
                              evidence=o.get("evidence", []), evidence_digests=o.get("evidence_digests", {}), note=o.get("note", "")))
        inv["modules"].append(dict(id=m["id"], name=m["name"], workstream=m["workstream"], code_paths=code_paths(m["code_paths_raw"]),
                                   associated_work=m["associated_work"], known_blocker=m["blocker"], status=mo.get("status", "CANDIDATE"),
                                   independent_attestation=mo.get("independent_attestation"), reviewer_identity=mo.get("reviewer_identity"), tasks=tasks))
    for g in gates:
        inv["gates"].append(dict(id=g["id"], name=g["name"], items=[dict(text=i["text"], done=False) for i in g["items"]], status="OPEN"))
    return inv


def render_blocked(inv):
    L = ["# Open tasks that need something this workspace cannot supply (generated; do not edit)", "",
         "`EXTERNAL` = needs an independent reviewer, owner decision, legal/licence review, user study or third-party resource.",
         "`NEEDS_LIVE_ENV` = needs a real service, kernel, host or provider not available in the sandbox.", "",
         "Classes are keyword triage (`class_heuristic`), not proof.  Nothing here is marked done.", ""]
    for m in inv["modules"]:
        rows = [t for t in m["tasks"] if not t["done"] and t["class_heuristic"] in ("EXTERNAL", "NEEDS_LIVE_ENV")]
        if not rows: continue
        L.append(f"## {m['id']} — {m['name']}")
        L += [f"- `{t['id']}` [{t['class_heuristic']}] {t['text']}" for t in rows]; L.append("")
    return "\n".join(L) + "\n"


def problems(inv):
    P = []; seen = set()
    for m in inv["modules"]:
        if m["status"] not in STATUSES: P.append(f"{m['id']}: bad status {m['status']}")
        if m["status"] in ABOVE_CANDIDATE and not m["independent_attestation"]: P.append(f"{m['id']}: status {m['status']} without independent_attestation")
        if m["independent_attestation"] and not m["reviewer_identity"]: P.append(f"{m['id']}: attestation without reviewer_identity")
        for t in m["tasks"]:
            if t["id"] in seen: P.append(f"duplicate task {t['id']}")
            seen.add(t["id"])
            if t["done"]:
                if t["id"].endswith("-GATE") and not m["independent_attestation"]: P.append(f"{t['id']}: GATE done without attestation")
                if not t["evidence"]: P.append(f"{t['id']}: done without evidence")
                for e in t["evidence"]:
                    full = os.path.join(ROOT, e)
                    if not os.path.isfile(full): P.append(f"{t['id']}: evidence missing {e}")
                    elif t["evidence_digests"].get(e) != digest(e): P.append(f"{t['id']}: evidence digest mismatch {e}")
    return P


def main():
    inv = render(); text = json.dumps(inv, indent=1, sort_keys=True) + "\n"
    if "--check" in sys.argv:
        ok = os.path.exists(OUT) and open(OUT).read() == text and os.path.exists(BLK) and open(BLK).read() == render_blocked(inv)
        P = problems(inv)
        for p in P: print("PROBLEM:", p)
        print("current" if ok else "stale"); sys.exit(0 if ok and not P else 1)
    os.makedirs(os.path.dirname(OUT), exist_ok=True); open(OUT, "w").write(text); open(BLK, "w").write(render_blocked(inv))
    n = sum(len(m["tasks"]) for m in inv["modules"]); d = sum(t["done"] for m in inv["modules"] for t in m["tasks"])
    from collections import Counter
    c = Counter(t["class_heuristic"] for m in inv["modules"] for t in m["tasks"] if not t["done"])
    print(f"modules={len(inv['modules'])} tasks={n} done={d} open_by_class={dict(c)} gates={len(inv['gates'])}")
    miss = [(m["id"], p["path"]) for m in inv["modules"] for p in m["code_paths"] if not p["exists"]]
    print("missing code paths:", miss)

if __name__ == "__main__": main()
