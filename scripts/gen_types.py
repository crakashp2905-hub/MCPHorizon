#!/usr/bin/env python3
"""Generate TypeScript, Python (TypedDict) and Rust (serde) types from horizon/schema_defs.py. `--check` detects drift."""
import re, sys
from pathlib import Path
ROOT = Path(__file__).resolve().parents[1]; sys.path.insert(0, str(ROOT))
from horizon.schema_defs import ALL

def pascal(s): return "".join(p[:1].upper() + p[1:] for p in re.split(r"[^A-Za-z0-9]+", s) if p)
def snake_ok(s): return re.fullmatch(r"[a-z_][a-z0-9_]*", s) is not None

class Gen:
    def __init__(self): self.ts, self.py, self.rs, self.seen = [], [], [], set()
    # ---- TypeScript
    def tstype(self, s, name):
        if "const" in s: return json_lit(s["const"])
        if "enum" in s: return " | ".join(json_lit(x) for x in s["enum"])
        t = s.get("type")
        if isinstance(t, list):
            return " | ".join(self.tstype({**s, "type": x}, name) for x in t)
        if t == "string": return "string"
        if t in ("integer", "number"): return "number"
        if t == "boolean": return "boolean"
        if t == "null": return "null"
        if t == "array": return f"Array<{self.tstype(s['items'], name)}>" if "items" in s else "unknown[]"
        if t == "object":
            if "properties" not in s: return "Record<string, unknown>"
            req = set(s.get("required", []))
            body = "; ".join(f"{k}{'' if k in req else '?'}: {self.tstype(v, name + pascal(k))}" for k, v in s["properties"].items())
            return "{ " + body + " }"
        raise ValueError(s)
    # ---- Python
    def pytype(self, s):
        if "const" in s: return f"Literal[{s['const']!r}]"
        if "enum" in s: return "Literal[" + ", ".join(repr(x) for x in s["enum"]) + "]"
        t = s.get("type")
        if isinstance(t, list): return "Union[" + ", ".join(self.pytype({**s, "type": x}) for x in t) + "]"
        m = {"string": "str", "integer": "int", "number": "float", "boolean": "bool", "null": "None"}
        if t in m: return m[t]
        if t == "array": return f"List[{self.pytype(s['items'])}]" if "items" in s else "List[Any]"
        if t == "object": return "Dict[str, Any]"
        raise ValueError(s)

def json_lit(x): import json; return json.dumps(x)

def rust_for(kind, schema):
    out, n = [], [0]
    def ty(s, name):
        if "const" in s: return "String"
        if "enum" in s:
            vs = s["enum"]; en = pascal(name)
            out.append("#[derive(Debug, Clone, PartialEq, Serialize, Deserialize)]\npub enum %s {\n%s}\n" % (en, "".join(
                f'    #[serde(rename = "{v}")]\n    V{i}_{re.sub(r"[^A-Za-z0-9]", "_", v)},\n' for i, v in enumerate(vs))))
            return en
        t = s.get("type")
        if isinstance(t, list):
            non = [x for x in t if x != "null"]; inner = ty({**s, "type": non[0]}, name)
            return f"Option<{inner}>" if "null" in t else inner
        if t == "string": return "String"
        if t == "integer": return "i64"
        if t == "number": return "f64"
        if t == "boolean": return "bool"
        if t == "array": return f"Vec<{ty(s['items'], name + 'Item')}>" if "items" in s else "Vec<serde_json::Value>"
        if t == "object":
            if "properties" not in s: return "serde_json::Map<String, serde_json::Value>"
            sn = pascal(name); req = set(s.get("required", [])); fields = []
            for k, v in s["properties"].items():
                ft = ty(v, name + pascal(k)); opt = k not in req and not ft.startswith("Option<")
                attr = '    #[serde(skip_serializing_if = "Option::is_none", default)]\n' if opt else ""
                if k not in req and ft.startswith("Option<"): attr = '    #[serde(skip_serializing_if = "Option::is_none", default)]\n'
                fields.append(f'{attr}    #[serde(rename = "{k}")]\n    pub f_{re.sub(r"[^a-z0-9]", "_", k.lower())}: {"Option<" + ft + ">" if opt else ft},\n')
            out.append("#[derive(Debug, Clone, PartialEq, Serialize, Deserialize)]\n#[serde(deny_unknown_fields)]\npub struct %s {\n%s}\n" % (sn, "".join(fields)))
            return sn
        raise ValueError(s)
    top = pascal(kind)
    if "oneOf" in schema:  # tagged union on `kind`
        names = []
        for d, ds in schema["$defs"].items():
            names.append((d, ty(ds, top + pascal(d))))
        out.append("#[derive(Debug, Clone, PartialEq, Serialize, Deserialize)]\n#[serde(untagged)]\npub enum %s {\n%s}\n" % (top, "".join(f"    {pascal(d)}({n}),\n" for d, n in names)))
    else: ty(schema, top)
    return "".join(out)

def build():
    ts = ["// GENERATED by scripts/gen_types.py from horizon/schema_defs.py — do not edit.\n"]
    py = ["# GENERATED by scripts/gen_types.py from horizon/schema_defs.py — do not edit.\nfrom typing import Any, Dict, List, Literal, NotRequired, TypedDict, Union\n"]
    rs = ["// GENERATED by scripts/gen_types.py — do not edit.\n#![allow(non_camel_case_types, dead_code)]\nuse serde::{Deserialize, Serialize};\n"]
    g = Gen()
    for kind, sch in ALL.items():
        name = pascal(kind)
        if "oneOf" in sch:
            alts = []
            for d, ds in sch["$defs"].items():
                ts.append(f"export type {name}{pascal(d)} = {g.tstype(ds, name + pascal(d))};\n"); alts.append(f"{name}{pascal(d)}")
                req = set(ds.get("required", []))
                py.append(f"class {name}{pascal(d)}(TypedDict):\n" + "".join(f"    {k}: {g.pytype(v) if k in req else 'NotRequired[' + g.pytype(v) + ']'}\n" for k, v in ds["properties"].items()))
            ts.append(f"export type {name} = {' | '.join(alts)};\n"); py.append(f"{name} = Union[{', '.join(alts)}]\n")
        else:
            ts.append(f"export type {name} = {g.tstype(sch, name)};\n")
            req = set(sch.get("required", []))
            py.append(f"class {name}(TypedDict):\n" + "".join(f"    {k}: {g.pytype(v) if k in req else 'NotRequired[' + g.pytype(v) + ']'}\n" for k, v in sch["properties"].items()))
        rs.append(rust_for(kind, sch))
    return {"types/typescript/horizon_types.ts": "".join(ts), "types/python/horizon_types.py": "\n".join(py), "types/rust/horizon_types.rs": "\n".join(rs)}

if __name__ == "__main__":
    drift = 0
    for rel, text in build().items():
        p = ROOT / rel
        if "--check" in sys.argv:
            if not p.exists() or p.read_text() != text: print("DRIFT", rel); drift += 1
        else: p.parent.mkdir(parents=True, exist_ok=True); p.write_text(text)
    raise SystemExit(1 if drift else 0)
