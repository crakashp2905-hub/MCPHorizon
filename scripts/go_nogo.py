#!/usr/bin/env python3
"""P22-18: GO/NO-GO from EXECUTABLE evidence. Runs each gate's test modules; a gate is CANDIDATE only if they pass AND no external requirement is outstanding. Never reports VERIFIED/MET for gates with unmet external requirements."""
import json, subprocess, sys
from pathlib import Path
REPO = Path(__file__).resolve().parents[1]
GATES = {
 "GX1 per-action proof validity": (["tests.p13.test_authz"], "reviewed primitives: independent cryptography/API review (P13-16) NOT done; proofs not wired into production gates"),
 "GX2 protocol equivalence": (["tests.p14.test_equiv"], None),
 "GX3 delegation": (["tests.p15.test_deleg"], None),
 "GX4 epistemic": (["tests.p16.test_epist"], "independent ground-truth fixtures NOT available; fixtures self-authored"),
 "GX5 memory": (["tests.p18.test_memory"], None),
 "GX6 version drift": (["tests.p19.test_attest"], None),
 "GX7 transactions": (["tests.p17.test_txn"], None),
 "GX8 comparative research": (["tests.p9.test_study"], "no advanced module shown to beat a STRONG independent baseline (earlier P9: B3 tied full; P15-P20 baselines are author-written)"),
 "GX9 auditability": ([], "independent reviewer reproduction (P22-16) NOT done"),
}
PAPERS = {"Paper A (protocol parity + actual-effect authorization)": ["GX2 protocol equivalence", "GX8 comparative research"], "Paper B (typed epistemic evidence)": ["GX4 epistemic", "GX8 comparative research"], "Paper C (cross-session benchmark)": ["GX5 memory", "GX9 auditability"]}


def passes(mods):
    for m in mods:
        r = subprocess.run([sys.executable, "-W", "ignore", "-m", "unittest", m], cwd=REPO, capture_output=True)
        if r.returncode: return False
    return True


def main():
    rows, status = [], {}
    for g, (mods, ext) in GATES.items():
        ok = passes(mods) if mods else False
        st = "NOT MET" if ext else ("CANDIDATE (synthetic/scripted evidence only)" if ok else "FAILING")
        status[g] = st.startswith("CANDIDATE"); rows.append((g, st, "tests " + ("pass" if ok else ("n/a" if not mods else "FAIL")), ext or "none outstanding in this repo; still needs independent replication before any VERIFIED claim"))
    md = ["# GO / NO-GO (generated by scripts/go_nogo.py)", "", "| Gate | Status | Executable evidence | Outstanding |", "|---|---|---|---|"] + [f"| {a} | {b} | {c} | {d} |" for a, b, c, d in rows]
    md += ["", "## Papers", ""] + [f"- **{p}**: {'GO' if all(status[g] for g in gs) else 'NO-GO'} (needs {', '.join(gs)})" for p, gs in PAPERS.items()]
    release = all(status.values()); md += ["", f"## Release / strong-security-claim decision: **{'GO' if release else 'NO-GO'}**", "", "Candidate-level components may be used for research and internal evaluation only. No gate is claimed VERIFIED."]
    out = "\n".join(md) + "\n"
    if "--check" in sys.argv:
        cur = (REPO / "docs/evidence/GO_NO_GO.md").read_text() if (REPO / "docs/evidence/GO_NO_GO.md").exists() else ""
        if cur != out: print("GO_NO_GO.md is stale; run scripts/go_nogo.py"); raise SystemExit(1)
        print("go/no-go doc up to date"); return
    (REPO / "docs/evidence/GO_NO_GO.md").write_text(out); print(out)


if __name__ == "__main__": main()
